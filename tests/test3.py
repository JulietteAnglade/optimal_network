import os
import sys
import numpy as np

sys.path.insert(0, os.path.abspath(os.path.dirname(__file__)))
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from scripts.run import run
from model_solver.network_encoder import ModeOfTransport
from model_solver.functions import (
    CobbDouglasUtility,
    CobbDouglasProduction,
    IcebergTau,
    BPRTime,
)


def main():

    # ============================================================
    # 1. NETWORK
    # ============================================================

    n_locations = 4
    n_modes = 2

    # ------------------------------------------------------------
    # Interpretation
    #
    # 0 : financial / business center
    # 1 : manufacturing belt
    # 2 : residential suburb
    # 3 : logistics / freight hub
    # ------------------------------------------------------------

    types_of_modes = [
        ModeOfTransport(
            name='Car',
            speed=50.0,
            cost_per_km=1.0,
        ),
        ModeOfTransport(
            name='Train',
            speed=95.0,
            cost_per_km=0.45,
        ),
    ]

    # ------------------------------------------------------------
    # Distances (km)
    # ------------------------------------------------------------

    distance_matrix = np.array([
        [0.0, 18.0, 28.0, 36.0],
        [18.0, 0.0, 14.0, 20.0],
        [28.0, 14.0, 0.0, 18.0],
        [36.0, 20.0, 18.0, 0.0],
    ])

    # ============================================================
    # 2. INITIAL INFRASTRUCTURE
    # ============================================================

    # ------------------------------------------------------------
    # IMPORTANT:
    # Start from moderate infrastructure,
    # NOT from all ones,
    # otherwise congestion explodes too fast.
    #
    # Shape = (4,4,2)
    # last dimension:
    # [car, train]
    # ------------------------------------------------------------

    current_infra_level = np.array([

        # --------------------------------------------------------
        # FROM 0
        # --------------------------------------------------------
        [
            [2.5, 3.0],
            [2.0, 2.8],
            [1.4, 1.2],
            [1.2, 2.0],
        ],

        # --------------------------------------------------------
        # FROM 1
        # --------------------------------------------------------
        [
            [2.0, 2.8],
            [2.5, 3.0],
            [2.2, 1.5],
            [2.0, 2.8],
        ],

        # --------------------------------------------------------
        # FROM 2
        # --------------------------------------------------------
        [
            [1.4, 1.2],
            [2.2, 1.5],
            [2.8, 2.0],
            [1.6, 1.1],
        ],

        # --------------------------------------------------------
        # FROM 3
        # --------------------------------------------------------
        [
            [1.2, 2.0],
            [2.0, 2.8],
            [1.6, 1.1],
            [3.0, 3.2],
        ],
    ])

    # ============================================================
    # 3. CAPACITIES
    # ============================================================

    # ------------------------------------------------------------
    # IMPORTANT:
    # capacities are MUCH smaller than before.
    #
    # Goal:
    # make congestion economically relevant.
    #
    # You want:
    #
    # Q / (C * I) ~ 0.5 - 1.5
    #
    # on important corridors.
    # ------------------------------------------------------------

    capacity = np.array([

        # --------------------------------------------------------
        # FROM 0
        # --------------------------------------------------------
        [
            [12.0, 18.0],
            [10.0, 16.0],
            [6.0, 7.0],
            [5.0, 12.0],
        ],

        # --------------------------------------------------------
        # FROM 1
        # --------------------------------------------------------
        [
            [10.0, 16.0],
            [12.0, 18.0],
            [8.0, 8.0],
            [8.0, 14.0],
        ],

        # --------------------------------------------------------
        # FROM 2
        # --------------------------------------------------------
        [
            [6.0, 7.0],
            [8.0, 8.0],
            [10.0, 10.0],
            [6.0, 6.0],
        ],

        # --------------------------------------------------------
        # FROM 3
        # --------------------------------------------------------
        [
            [5.0, 12.0],
            [8.0, 14.0],
            [6.0, 6.0],
            [12.0, 18.0],
        ],
    ])

    # ============================================================
    # 4. TRANSPORT CONSTRAINTS
    # ============================================================

    constraints = np.array([
        [1, 1],   # car
        [1, 1],   # train
    ], dtype=bool)

    # ============================================================
    # 5. ECONOMY
    # ============================================================

    n_sectors = 3

    # ------------------------------------------------------------
    # 0 : advanced services
    # 1 : manufacturing
    # 2 : logistics
    # ------------------------------------------------------------

    # ============================================================
    # 6. PRODUCTIVITY
    # ============================================================

    # ------------------------------------------------------------
    # IMPORTANT:
    # moderate productivity differences only.
    #
    # Too much dispersion causes:
    # - agglomeration collapse
    # - exploding congestion
    # - instability
    # ------------------------------------------------------------

    A = np.array([

        # services
        [1.35, 0.95, 0.85, 0.95],

        # manufacturing
        [0.90, 1.30, 0.95, 1.05],

        # logistics
        [0.80, 1.00, 0.85, 1.40],
    ])

    # ============================================================
    # 7. PRODUCTION ELASTICITIES
    # ============================================================

    # ------------------------------------------------------------
    # IMPORTANT:
    # strong decreasing returns.
    #
    # total RTS around:
    # 0.82 - 0.90
    #
    # VERY IMPORTANT for stability.
    # ------------------------------------------------------------

    aH = np.array([
        0.50,
        0.48,
        0.45,
    ])

    aL = np.array([
        0.20,
        0.22,
        0.20,
    ])

    # ------------------------------------------------------------
    # IMPORTANT:
    # much weaker IO network than before.
    #
    # This avoids production explosions.
    # ------------------------------------------------------------

    aQ = np.array([
        [0.00, 0.05, 0.06],
        [0.06, 0.00, 0.07],
        [0.05, 0.05, 0.00],
    ])

    production_function = CobbDouglasProduction(
        A=A,
        aH=aH,
        aL=aL,
        aQ=aQ,
    )

    # ============================================================
    # 8. HOUSEHOLD PREFERENCES
    # ============================================================

    utility_function = CobbDouglasUtility(

        alpha_c=np.array([

            # services workers
            [0.45, 0.18, 0.12],

            # manufacturing workers
            [0.20, 0.42, 0.15],

            # logistics workers
            [0.20, 0.20, 0.35],
        ]),

        # housing
        alpha_l=np.array([
            0.15,
            0.15,
            0.15,
        ]),

        # leisure
        alpha_f=np.array([
            0.10,
            0.10,
            0.10,
        ]),
    )

    # ============================================================
    # 9. LAND
    # ============================================================

    # ------------------------------------------------------------
    # CBD scarce,
    # suburb abundant.
    # ------------------------------------------------------------

    L_bar = np.array([
        4.0,    # CBD
        7.0,    # manufacturing
        14.0,   # suburb
        9.0,    # logistics
    ])

    # ============================================================
    # 10. POPULATION
    # ============================================================

    # ------------------------------------------------------------
    # IMPORTANT:
    # start SMALL.
    #
    # You can later increase:
    # 50 -> 80 -> 120 -> 200
    #
    # using warm starts.
    # ------------------------------------------------------------

    q_bar = 50.0

    H_bar = 1.0

    # ============================================================
    # 11. INFRASTRUCTURE BUDGET
    # ============================================================

    # ------------------------------------------------------------
    # Moderate scarcity.
    # ------------------------------------------------------------

    K = 10.0

    # ============================================================
    # 12. TRANSPORT / CONGESTION
    # ============================================================

    # ------------------------------------------------------------
    # iceberg dependence by sector
    # ------------------------------------------------------------

    sector_dependance_tau = np.array([
        0.01,   # services
        0.03,   # manufacturing
        0.05,   # logistics
    ])

    tau_link = IcebergTau
    t_link = BPRTime

    # ------------------------------------------------------------
    # commuting weight
    # ------------------------------------------------------------

    d_w = 1.0

    # ------------------------------------------------------------
    # freight intensity
    # ------------------------------------------------------------

    phi = np.array([
        0.6,
        1.2,
        1.8,
    ])

    # ============================================================
    # 13. LOGIT DISPERSION
    # ============================================================

    sigma = np.array([
        0.55,
        0.60,
        0.65,
    ])

    sigma_tilde = 0.80

    # ============================================================
    # 14. ALGORITHM PARAMETERS
    # ============================================================

    # ------------------------------------------------------------
    # IMPORTANT:
    # slower updates -> much more stable.
    # ------------------------------------------------------------

    T_outer = 500
    T_inner = 500

    eta_p = 0.01
    eta_w = 0.01
    eta_r = 0.01

    eta_beta = 0.01
    eta_I = 0.01
    eta_H = 0.005

    alpha_Q = 0.03
    alpha_Qhat = 0.03

    eta_gamma = 0.05

    tol_outer = 1e-5
    tol_inner = 1e-5

    verbose = True
    log_every = 25

    decay_start = 2000
    decay_type = 'sqrt'

    example_name = 'stable_4loc_2modes_3sectors'

    # ============================================================
    # 15. RUN
    # ============================================================

    run(
        n_locations,
        n_modes,
        types_of_modes,
        distance_matrix,
        current_infra_level,
        capacity,
        constraints,
        n_sectors,
        production_function,
        utility_function,
        L_bar,
        H_bar,
        q_bar,
        K,
        sector_dependance_tau,
        tau_link,
        t_link,
        d_w,
        phi,
        sigma,
        sigma_tilde,
        T_outer,
        eta_p,
        eta_w,
        eta_r,
        eta_beta,
        eta_I,
        eta_H,
        T_inner,
        alpha_Q,
        alpha_Qhat,
        eta_gamma,
        tol_outer,
        tol_inner,
        verbose,
        log_every,
        decay_start,
        decay_type,
        example_name,
    )


if __name__ == '__main__':
    main()